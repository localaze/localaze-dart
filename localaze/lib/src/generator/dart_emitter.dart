/// Turns a [GenerationPlan] into Dart source.
///
/// Every decision was made by the plan. This file only spells it, which is
/// why it has no failure path: a plan that reached here compiles.
library;

import 'plan.dart';

/// Words Dart will not accept as an identifier. A parameter or accessor that
/// would be one takes a trailing underscore, since Dart has no escape.
const Set<String> _reserved = <String>{
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue',
  'default', 'do', 'else', 'enum', 'extends', 'false', 'final', 'finally',
  'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', 'return', 'super',
  'switch', 'this', 'throw', 'true', 'try', 'var', 'void', 'while', 'with',
};

const Map<String, String> _types = <String, String>{
  'STRING': 'String',
  'NUMBER': 'num',
  'DATETIME': 'DateTime',
};

String _escape(String identifier) =>
    _reserved.contains(identifier) ? '${identifier}_' : identifier;

/// The Dart source for [plan].
String emitDart(GenerationPlan plan) {
  final out = StringBuffer();
  _header(out, plan);
  _type(out, plan);
  _signature(out, plan);
  _plurals(out, plan);
  _compiledIn(out, plan);
  return out.toString();
}

void _header(StringBuffer out, GenerationPlan plan) {
  out
    ..writeln('// GENERATED BY LOCALAZE — DO NOT EDIT.')
    ..writeln('// Regenerate with `dart run localaze:generate`. '
        'Hand edits are lost.')
    ..writeln('//')
    ..writeln('// environment: ${_comment(plan.environment)}')
    ..writeln('// version:     ${_comment(plan.version)}')
    ..writeln('// hash:        ${_comment(plan.contentHash)}')
    ..writeln('// source:      ${_comment(plan.sourceLanguage)}')
    ..writeln('//')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import 'package:localaze/localaze.dart';")
    ..writeln();
}

void _type(StringBuffer out, GenerationPlan plan) {
  final locales = plan.languages.map(_literal).join(', ');
  out
    ..writeln('/// Typed translations, generated from release '
        '${_comment(plan.version)}.')
    ..writeln('///')
    ..writeln('/// Every accessor is typed: a message that selects on a count '
        'cannot be')
    ..writeln('/// called without one, and the compiler checks it.')
    ..writeln('class Localaze {')
    ..writeln('  Localaze._(this.runtime);')
    ..writeln()
    ..writeln('  /// The runtime behind these accessors, for the update '
        'machinery.')
    ..writeln('  final LocalazeRuntime runtime;')
    ..writeln()
    ..writeln('  /// The languages this release carries, source first.')
    ..writeln('  static const List<String> supportedLocales = '
        '<String>[$locales];')
    ..writeln()
    ..writeln('  static const String sourceLocale = '
        '${_literal(plan.sourceLanguage)};')
    ..writeln()
    ..writeln('  /// The release this code was generated from. The update '
        'policy')
    ..writeln('  /// compares every fetched catalog against it.')
    ..writeln('  static const String generatedFrom = ${_literal(plan.version)};')
    ..writeln()
    ..writeln('  static const String contentHash = '
        '${_literal(plan.contentHash)};')
    ..writeln()
    ..writeln('  /// Translations for [locale]. A locale this release does not '
        'carry')
    ..writeln("  /// starts from the source language's compiled-in catalog.")
    ..writeln('  static Localaze forLocale(String locale, '
        'LocalazeConfig config) {')
    ..writeln('    return Localaze._(LocalazeRuntime(')
    ..writeln('      locale: locale,')
    ..writeln('      config: config,')
    ..writeln('      signature: _signature,')
    ..writeln('      compiledIn: _compiledIn[locale] ?? '
        '_compiledIn[sourceLocale]!,')
    ..writeln('      pluralResolver: (num value) => _plural(locale, value),')
    ..writeln('    ));')
    ..writeln('  }');

  for (final key in plan.keys) {
    out.writeln();
    _accessor(out, key);
  }
  out
    ..writeln('}')
    ..writeln();
}

void _accessor(StringBuffer out, PlannedKey key) {
  if (key.preview.isNotEmpty) {
    out.writeln('  /// `${_comment(key.preview).replaceAll('`', "'")}`');
  }
  if (key.selector != null) {
    if (key.preview.isNotEmpty) out.writeln('  ///');
    out.writeln('  /// Selects on `${key.selector}`, so it cannot be called '
        'without it.');
  }

  final name = _escape(key.accessor);
  if (key.params.isEmpty) {
    out.writeln('  String get $name => this.runtime.render('
        '${_literal(key.key)});');
    return;
  }

  final params = key.params
      .map((p) => 'required ${_types[p.type]} ${_escape(p.identifier)}')
      .join(', ');
  final args = key.params
      .map((p) => '${_literal(p.name)}: ${_escape(p.identifier)}')
      .join(', ');

  out
    ..writeln('  String $name({$params}) => this.runtime.render(')
    ..writeln('        ${_literal(key.key)},')
    ..writeln('        args: <String, Object?>{$args},');
  final selector = key.selector;
  if (selector != null) {
    final identifier = key.params.firstWhere((p) => p.name == selector);
    out.writeln('        selector: ${_escape(identifier.identifier)},');
  }
  out.writeln('      );');
}

void _signature(StringBuffer out, GenerationPlan plan) {
  out
    ..writeln('// ── Signature ──────────────────────────────────────────────'
        '──────────────────')
    ..writeln('// Names and types. A fetched catalog is refused unless every '
        'key here is')
    ..writeln('// present and every parameter still matches.')
    ..writeln()
    ..writeln('final LocalazeSignature _signature =')
    ..writeln('    LocalazeSignature.of(<String, List<(String, String)>>{');
  for (final key in plan.keys) {
    final params = key.params
        .map((p) => '(${_literal(p.name)}, ${_literal(p.type)})')
        .join(', ');
    out.writeln('  ${_literal(key.key)}: <(String, String)>[$params],');
  }
  out
    ..writeln('});')
    ..writeln();
}

void _plurals(StringBuffer out, GenerationPlan plan) {
  out
    ..writeln('// ── Plural rules ───────────────────────────────────────────'
        '──────────────────')
    ..writeln("// Each language's CLDR rules, compiled by the server and "
        'published in the')
    ..writeln('// manifest. No CLDR data ships and no MF2 is parsed on '
        'device.')
    ..writeln()
    ..writeln('String? _plural(String locale, num value) {')
    ..writeln('  switch (locale) {');
  for (final plural in plan.plurals) {
    out
      ..writeln('    case ${_literal(plural.language)}:')
      ..writeln('      return ${_resolverName(plural.language)}(value);');
  }
  out
    ..writeln('    default:')
    ..writeln('      return null;')
    ..writeln('  }')
    ..writeln('}');

  for (final plural in plan.plurals) {
    out.writeln();
    _resolver(out, plural);
  }
  out.writeln();
}

void _resolver(StringBuffer out, PlannedPlural plural) {
  final name = _resolverName(plural.language);
  if (plural.categories.isEmpty) {
    out.writeln('String? $name(num value) => null;');
    return;
  }

  final usesV = plural.uses('v');
  final usesI = usesV || plural.uses('i');

  out
    ..writeln('String? $name(num value) {')
    ..writeln('  final num n = value.abs();')
    ..writeln('  if (!n.isFinite || n >= 1e15) return null;');
  if (usesI) out.writeln('  final int i = n.floor();');
  if (usesV) out.writeln('  final int v = n == i ? 0 : 1;');
  out.writeln();
  for (final (category, condition) in plural.categories) {
    out.writeln('  if ($condition) return ${_literal(category)};');
  }
  out
    ..writeln('  return null;')
    ..writeln('}');
}

void _compiledIn(StringBuffer out, GenerationPlan plan) {
  out
    ..writeln('// ── Compiled-in catalogs ───────────────────────────────────'
        '──────────────────')
    ..writeln('// The floor. An app whose asset is missing or unreadable '
        'still renders')
    ..writeln('// text rather than key names.')
    ..writeln()
    ..writeln('const Map<String, String> _compiledIn = <String, String>{');
  for (final language in plan.languages) {
    out.writeln('  ${_literal(language)}: '
        '${_literal(plan.catalogs[language]!)},');
  }
  out.writeln('};');
}

/// `pt-BR` becomes `_pluralPtBr`.
String _resolverName(String language) {
  final segments = language.split(RegExp(r'[-_]'));
  return '_plural${segments.map((segment) => segment.isEmpty ? '' : segment[0].toUpperCase() + segment.substring(1).toLowerCase()).join()}';
}

/// A single-quoted Dart string literal holding exactly [value].
String _literal(String value) {
  final out = StringBuffer("'");
  for (final rune in value.runes) {
    switch (rune) {
      case 0x5C:
        out.write(r'\\');
      case 0x27:
        out.write(r"\'");
      case 0x24:
        out.write(r'\$');
      case 0x0A:
        out.write(r'\n');
      case 0x0D:
        out.write(r'\r');
      case 0x09:
        out.write(r'\t');
      default:
        if (rune < 0x20 || rune == 0x7F) {
          out.write('\\u{${rune.toRadixString(16)}}');
        } else {
          out.writeCharCode(rune);
        }
    }
  }
  out.write("'");
  return out.toString();
}

/// Text safe inside a `//` or `///` comment: one line, nothing else.
String _comment(String value) =>
    value.replaceAll(RegExp(r'[\r\n  ]+'), ' ');
